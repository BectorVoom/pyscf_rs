/// The Householder factorization and the closed form `|det| / ||c0 x c1||` are
/// two independent routes to `|R[2,2]|`. If either is wrong they diverge.
#[test]
fn householder_r22_agrees_with_the_closed_form() {
    let mut rng = Lcg(0x5DEECE66D);
    for _ in 0..2000 {
        let cols = [
            [rng.next_f64(), rng.next_f64(), rng.next_f64()],
            [rng.next_f64(), rng.next_f64(), rng.next_f64()],
            [rng.next_f64(), rng.next_f64(), rng.next_f64()],
        ];
        let closed = qr_r22_abs_closed_form(&cols);
        // Skip near-degenerate draws where both routes are dominated by
        // cancellation rather than by either algorithm.
        if !closed.is_finite() || closed < 1e-3 {
            continue;
        }
        let house = qr_r22_abs(&cols);
        assert!(
            rel(house, closed) < 1e-9,
            "|R22| disagree: householder {house:.17e} vs closed {closed:.17e} for {cols:?}"
        );
    }
}

/// Same check on the real reciprocal lattices, at a much tighter tolerance —
/// these are well conditioned.
#[test]
fn r22_routes_agree_on_the_reference_lattices() {
    for (name, a) in LATTICES {
        let r = qr_heights(&a).expect("non-singular");
        // Rebuild b to feed the closed form the identical columns.
        let heights = closed_form_heights(&a);
        for i in 0..3 {
            assert!(
                rel(r[i], heights[i]) < 1e-13,
                "{name} axis {i}: {} vs closed {}",
                r[i],
                heights[i]
            );
        }
    }
}

/// `qr_heights(a)[i] == 2*pi / ||a_i||`, exactly, for ANY lattice.
///
/// `b_i . a_j = 2*pi*delta_ij` by construction, so `a_2` is the (only)
/// direction orthogonal to both `b_0` and `b_1`; the component of `b_2`
/// perpendicular to `span(b_0, b_1)` is therefore `b_2 . a_2 / ||a_2|| =
/// 2*pi / ||a_2||`, and the same argument permutes to the other two axes. That
/// identity is completely independent of the QR route and pins every height to
/// a one-line closed form.
#[test]
fn qr_heights_equal_two_pi_over_the_lattice_vector_lengths() {
    for (name, a) in LATTICES {
        let r = qr_heights(&a).expect("non-singular");
        for i in 0..3 {
            let want = 2.0 * PI / norm(&a[i]);
            assert!(
                rel(r[i], want) < 1e-14,
                "{name} axis {i}: qr height {} vs 2*pi/||a_{i}|| {}",
                r[i],
                want
            );
        }
    }
    // ... and on random lattices, where a wrong column permutation could not
    // hide behind the reference cells' symmetry.
    let mut rng = Lcg(0xDEADBEEF);
    for _ in 0..500 {
        let a = [
            [rng.next_f64(), rng.next_f64(), rng.next_f64()],
            [rng.next_f64(), rng.next_f64(), rng.next_f64()],
            [rng.next_f64(), rng.next_f64(), rng.next_f64()],
        ];
        if det3(&a).abs() < 1e-2 {
            continue;
        }
        let r = qr_heights(&a).expect("non-singular");
        for i in 0..3 {
            let want = 2.0 * PI / norm(&a[i]);
            assert!(
                rel(r[i], want) < 1e-9,
                "axis {i}: {} vs {want} for {a:?}",
                r[i]
            );
        }
    }
}

/// `2*ceil(Gmax) + 1` — odd, at least 1, never shrinking as the cutoff rises,
/// and exactly `[1,1,1]` at zero cutoff.
#[test]
fn mesh_is_odd_and_monotone() {
    for (name, a) in LATTICES {
        assert_eq!(cutoff_to_mesh(&a, 0.0).expect("ok"), [1, 1, 1], "{name}");
        let mut last = [0_usize; 3];
        for ke in [1.0, 10.0, 50.0, 100.0, 500.0, 2000.0] {
            let m = cutoff_to_mesh(&a, ke).expect("ok");
            for i in 0..3 {
                assert_eq!(m[i] % 2, 1, "{name} axis {i}: {} is not odd", m[i]);
                assert!(m[i] >= last[i], "{name} axis {i} shrank at ke = {ke}");
            }
            last = m;
        }
    }
}

/// `mesh_to_cutoff(cutoff_to_mesh(a, ke)) >= ke`, and the mesh one step
/// smaller would NOT reach it — i.e. `cutoff_to_mesh` returns the minimal
/// sufficient odd mesh.
#[test]
fn cutoff_to_mesh_is_the_minimal_sufficient_mesh() {
    for (name, a) in LATTICES {
        for ke in [5.0, 50.0, 100.0, 422.9, 1077.5] {
            let m = cutoff_to_mesh(&a, ke).expect("ok");
            let up = mesh_to_cutoff(&a, m).expect("ok");
            for i in 0..3 {
                assert!(
                    up[i] >= ke,
                    "{name} axis {i}: mesh {} resolves {} < {ke}",
                    m[i],
                    up[i]
                );
                if m[i] >= 3 {
                    let smaller = {
                        let mut s = m;
                        s[i] -= 2;
                        s
                    };
                    let down = mesh_to_cutoff(&a, smaller).expect("ok");
                    assert!(
                        down[i] < ke,
                        "{name} axis {i}: mesh {} would already reach {ke}; \
                         cutoff_to_mesh is not minimal",
                        smaller[i]
                    );
                }
            }
        }
    }
}

/// `gs = mesh // 2` and `gs_to_cutoff(gs) == mesh_to_cutoff(2*gs+1)`
/// (`pbc.py:830-836`).
#[test]
fn gs_helpers_are_the_documented_aliases() {
    for (name, a) in LATTICES {
        for ke in [50.0, 100.0, 400.0] {
            let mesh = cutoff_to_mesh(&a, ke).expect("ok");
            let gs = cutoff_to_gs(&a, ke).expect("ok");
            for i in 0..3 {
                assert_eq!(gs[i], mesh[i] / 2, "{name} axis {i}");
            }
            let a_ = gs_to_cutoff(&a, gs).expect("ok");
            let b_ = mesh_to_cutoff(&a, [2 * gs[0] + 1, 2 * gs[1] + 1, 2 * gs[2] + 1]).expect("ok");
            assert_eq!(a_, b_, "{name}");
        }
    }
}

/// `mesh_to_cutoff` uses `gs = (mesh - 1) // 2`, so an even mesh resolves the
/// same cutoff as the odd one below it, and a mesh of 0 or 1 resolves nothing.
#[test]
fn mesh_to_cutoff_floors_to_the_odd_mesh_below() {
    let a = LATTICES[0].1;
    assert_eq!(
        mesh_to_cutoff(&a, [16, 16, 16]).expect("ok"),
        mesh_to_cutoff(&a, [15, 15, 15]).expect("ok")
    );
    assert_eq!(mesh_to_cutoff(&a, [1, 1, 1]).expect("ok"), [0.0, 0.0, 0.0]);
    assert_eq!(mesh_to_cutoff(&a, [0, 0, 0]).expect("ok"), [0.0, 0.0, 0.0]);
}

/// A singular lattice and a bad cutoff are errors, never NaN meshes.
#[test]
fn degenerate_inputs_are_errors() {
    let singular = [[1.0, 2.0, 3.0], [2.0, 4.0, 6.0], [1.0, 0.0, 1.0]];
    assert!(cutoff_to_mesh(&singular, 100.0).is_err());
    assert!(mesh_to_cutoff(&singular, [15, 15, 15]).is_err());
    assert!(qr_heights(&singular).is_err());

    let a = LATTICES[0].1;
    assert!(cutoff_to_mesh(&a, -1.0).is_err());
    assert!(cutoff_to_mesh(&a, f64::NAN).is_err());
    assert!(cutoff_to_mesh(&a, f64::INFINITY).is_err());
}

/// A cubic lattice of side `L` has `b_i = 2*pi/L * e_i`, so every height is
/// `2*pi/L` and the mesh is isotropic — a case whose answer can be written down
/// by hand.
#[test]
fn cubic_lattice_has_the_analytic_mesh() {
    let l = 10.0_f64;
    let a = [[l, 0.0, 0.0], [0.0, l, 0.0], [0.0, 0.0, l]];
    let r = qr_heights(&a).expect("ok");
    for (i, ri) in r.iter().enumerate() {
        assert!(rel(*ri, 2.0 * PI / l) < 1e-15, "axis {i}: {ri}");
    }
    for ke in [10.0_f64, 100.0, 1000.0] {
        let want = ((2.0 * ke).sqrt() / (2.0 * PI / l)).ceil() as usize * 2 + 1;
        assert_eq!(cutoff_to_mesh(&a, ke).expect("ok"), [want, want, want]);
    }
}

