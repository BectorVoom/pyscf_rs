//! Plan 09-04 — `pyscf-pbc-tools::mesh` (port of `pyscf/pbc/tools/pbc.py:787-836`).
//!
//! `pyscf-pbc-tools` sits BELOW `pyscf-pbc-gto` in the dependency graph, so it
//! cannot reach the §9.2 reference `Cell`s. The lattices below are the same
//! five systems' `cell.lattice_vectors()` in Bohr, pasted as literals from the
//! upstream run that produced `crates/pyscf-pbc-gto/tests/cutoff.rs`'s
//! references (D-PBC-19).
//!
//! Tier 1 (invariants):
//!   * the Householder `|R[2,2]|` agrees with its closed form
//!     `|det(M)| / ||c0 x c1||` on random and lattice-shaped inputs;
//!   * `qr_heights` reproduces the reciprocal-cell heights
//!     `2*pi / |a_i . n_jk|` for any lattice;
//!   * every mesh axis is odd, monotone in the cutoff, and never
//!     under-resolves;
//!   * `mesh_to_cutoff` inverts `cutoff_to_mesh` up to the `ceil`;
//!   * `cutoff_to_gs` / `gs_to_cutoff` are the documented aliases;
//!   * a singular lattice and a negative cutoff are errors, not NaN.
//!
//! Tier 2: `cutoff_to_mesh` and `mesh_to_cutoff` against hard-coded upstream
//! values. NOTE the lattices here are UPSTREAM's, so these are exact-value
//! comparisons at 1e-12 — the `pyscf_core::Unit::Ang` gap documented in
//! `pyscf-pbc-gto/tests/cell_build.rs` enters only when a `Cell` builds the
//! lattice from Angstrom, which this crate never does.

