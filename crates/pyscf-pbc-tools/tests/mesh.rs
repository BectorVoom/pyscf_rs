// --- small local vector helpers, so this file needs no other imports -------

fn det3(m: &[[f64; 3]; 3]) -> f64 {
    m[0][0] * (m[1][1] * m[2][2] - m[1][2] * m[2][1])
        - m[0][1] * (m[1][0] * m[2][2] - m[1][2] * m[2][0])
        + m[0][2] * (m[1][0] * m[2][1] - m[1][1] * m[2][0])
}

fn cross(u: &[f64; 3], v: &[f64; 3]) -> [f64; 3] {
    [
        u[1] * v[2] - u[2] * v[1],
        u[2] * v[0] - u[0] * v[2],
        u[0] * v[1] - u[1] * v[0],
    ]
}

fn norm(v: &[f64; 3]) -> f64 {
    (v[0] * v[0] + v[1] * v[1] + v[2] * v[2]).sqrt()
}

/// The closed-form `|R[2,2]|` per axis, built from the same reciprocal vectors
/// `qr_heights` uses — the independent route for
/// [`r22_routes_agree_on_the_reference_lattices`].
fn closed_form_heights(a: &[[f64; 3]; 3]) -> [f64; 3] {
    let b = reciprocal_2pi(a);
    [
        qr_r22_abs_closed_form(&[b[1], b[2], b[0]]),
        qr_r22_abs_closed_form(&[b[2], b[0], b[1]]),
        qr_r22_abs_closed_form(&[b[0], b[1], b[2]]),
    ]
}

/// `2*pi*inv(a.T)`, one reciprocal vector per row — written out here rather
/// than imported so the check does not share code with the implementation.
fn reciprocal_2pi(a: &[[f64; 3]; 3]) -> [[f64; 3]; 3] {
    // b_i = 2*pi * (a_j x a_k) / det(a), the standard reciprocal-basis formula.
    let det = det3(a);
    let mut b = [[0.0_f64; 3]; 3];
    for (i, bi) in b.iter_mut().enumerate() {
        let c = cross(&a[(i + 1) % 3], &a[(i + 2) % 3]);
        for (t, bit) in bi.iter_mut().enumerate() {
            *bit = 2.0 * PI * c[t] / det;
        }
    }
    b
}
